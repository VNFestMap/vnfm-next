def normalize_china_province(value: str) -> tuple[str, bool]:
    raw = (value or "").strip()
    if not raw:
        return "", False
    if raw in CHINA_CANON:
        return CHINA_CANON[raw], True
    stripped = raw.replace("省", "").replace("市", "")
    if stripped in CHINA_CANON:
        return CHINA_CANON[stripped], True
    return raw, False


def normalize_japan_prefecture(value: str) -> tuple[str, bool]:
    raw = (value or "").strip()
    if not raw:
        return "", False
    if raw in JAPAN_CANON:
        return JAPAN_CANON[raw], True
    simplified = (
        raw.replace("県", "县")
        .replace("東", "东")
        .replace("岡", "冈")
        .replace("広", "广")
        .replace("島", "岛")
        .replace("長", "长")
        .replace("徳", "德")
        .replace("愛", "爱")
        .replace("児", "儿")
        .replace("縄", "绳")
        .replace("葉", "叶")
        .replace("宮", "宫")
        .replace("馬", "马")
        .replace("賀", "贺")
        .replace("鳥", "鸟")
        .replace("福島", "福岛")
        .replace("静岡", "静冈")
        .replace("千葉", "千叶")
        .replace("埼玉", "埼玉")
    )
    if simplified in JAPAN_CANON:
        return JAPAN_CANON[simplified], True
    return raw, False

